#   DATA n,w,h                      a sprite: texture number, width, height (index 0 = see-through)
#   DATA t,a,b,c,d,hue,shade        one command: t 1 filled rectangle a,b,c,d  2 rectangle outline  3 line a,b to c,d  4 filled ellipse centre a,b radius c, d/10 as high as wide
