static double checksum( const house_t* h ) {
    double ck = 0;
    for ( int i = 0; i < h->nwin; ++i ) {
        const hwin_t* w = &h->win[i];
        ck += floor( w->pos * 10 ) * 7 + floor( w->w * 10 ) * 3 + w->sill * 11 + w->head * 13 + w->kind * 17 + w->side * 101 + w->floor * 1009;
    }
    for ( int f = 0; f < 2; ++f ) {
        for ( int i = 0; i < h->nfu[f]; ++i ) {
            const hfurn_t* u = &h->fu[f][i];
            ck += floor( u->x1 * 10 ) + floor( u->y1 * 10 ) * 3 + floor( u->x2 * 10 ) * 5 + floor( u->y2 * 10 ) * 7 + u->color * 11;
        }
    }
    for ( int f = 0; f < 2; ++f ) {
        for ( int i = 0; i < h->nrm[f]; ++i ) {
            const hroom_t* r = &h->rm[f][i];
            ck += r->x1 * 3 + r->y1 * 5 + r->x2 * 7 + r->y2 * 11 + r->type * 13 + r->color * 17;
        }
    }
    for ( int f = 0; f < 2; ++f ) {
        for ( int i = 0; i < h->ndor[f]; ++i ) {
            const hdoor_t* d = &h->dor[f][i];
            ck += d->axis * 19 + d->x * 23 + d->y * 29 + d->w * 31;
        }
    }
    return ck;
}

static void test_gen( void ) {
    house_t h;
    for ( int n = 0; n < 200; ++n ) {
        const double* r = ref[n];
        house_gen_basic( &h, (int) r[0], (int64_t) r[1] );
        int bad = 0;
        if ( h.lx != r[2] || h.dy != r[3] || h.zr != r[4] || h.ez != r[5] || h.ss != (int) r[6] || h.nwin != (int) r[7] ) { bad = 1; }
        if ( h.nrm[0] != (int) r[8] || h.nrm[1] != (int) r[9] || h.ndor[0] != (int) r[10] || h.ndor[1] != (int) r[11] || h.nfu[0] != (int) r[12] || h.nfu[1] != (int) r[13] ) { bad = 2; }
        if ( fabs( checksum( &h ) - r[14] ) > 1e-6 ) { bad = 3; }
        if ( (int) floor( h.sx1 ) != (int) r[15] || (int) floor( h.sy1 ) != (int) r[16] || h.plc != (int) r[17] || h.rfc != (int) r[18] || h.att != (int) r[19] || h.chx != r[20] ) { bad = 4; }
        if ( bad ) { printf( "type %d seed %d differs from the BASIC generator (%d)\n", (int) r[0], (int) r[1], bad ); }
        CHECK( bad == 0 );
    }
    // the invariants of 500 more houses
    int nf = 0;
    for ( int t = 1; t <= 5; ++t ) {
        for ( int s = 100; s < 200; ++s ) {
            house_gen( &h, t, s );
            int bad = 0;
            if ( h.zr > 100 || h.zr < h.ez + 8 || h.ez > h.flz[1] + 34 || h.zr < 85 ) { bad = 1; }
            if ( h.lx < 124 || h.lx > 148 || h.dy < 100 || h.dy > 124 ) { bad = 2; }
            int n0 = t == 2 || t == 5 ? 7 : 6;
            if ( h.nrm[0] != n0 || h.nrm[1] != 5 ) { bad = 3; }
            for ( int f = 0; f < 2; ++f ) {
                for ( int i = 0; i < h.nrm[f]; ++i ) {
                    const hroom_t* r = &h.rm[f][i];
                    if ( r->x2 <= r->x1 || r->y2 <= r->y1 ) { bad = 4; }
                    if ( r->type <= 9 && ( r->x1 < HOUSE_TW || r->y1 < HOUSE_TW || r->x2 > h.lx - HOUSE_TW || r->y2 > h.dy - HOUSE_TW ) ) { bad = 5; }
                }
                for ( int i = 0; i < h.nfu[f]; ++i ) {
                    bool in = false;
                    for ( int j = 0; j < h.nrm[f]; ++j ) {
                        const hroom_t* r = &h.rm[f][j];
                        if ( h.fu[f][i].x1 >= r->x1 - 0.01 && h.fu[f][i].x2 <= r->x2 + 0.01 && h.fu[f][i].y1 >= r->y1 - 0.01 && h.fu[f][i].y2 <= r->y2 + 0.01 ) { in = true; }
                    }
                    if ( !in ) { bad = 6; }
                }
            }
            for ( int i = 0; i < h.nwin; ++i ) {
                const hwin_t* w = &h.win[i];
                if ( w->w <= 0 || w->head <= w->sill || w->side < 0 || w->side > 9 ) { bad = 7; }
                if ( w->side < 2 && ( w->pos - w->w / 2 < 0 || w->pos + w->w / 2 > h.lx + h.ai + 4 ) ) { bad = 7; }
                if ( ( w->side == 4 || w->side == 5 || w->side == 6 ) != ( t == 2 && w->side >= 4 && w->side <= 6 ) ) { bad = 8; }
                if ( w->side >= 7 && t != 5 ) { bad = 8; }
            }
            if ( t == 2 && ( h.ai < 45 || h.ai > 55 || h.ay < 50 || h.ay > 65 || h.rm[0][6].type != 10 ) ) { bad = 9; }
            if ( t == 5 && ( h.exx1 < HOUSE_TW + 4 || h.exx2 > h.lx - HOUSE_TW - 4 || h.rm[0][6].type != 11 || h.bw < 8 ) ) { bad = 9; }
            if ( h.wy - h.sy2 < 7.9 || h.sy1 < HOUSE_TW + 12 || h.sx2 - h.sx1 < 11.9 ) { bad = 10; }          // the stairs: a landing at the top, room for the doors at the foot, 1.2 m wide
            if ( bad ) { ++nf; printf( "house type %d seed %d fails check %d\n", t, s, bad ); }
        }
    }
    CHECK( nf == 0 );
    // the cheap size is the size of the house
    for ( int s = 1; s < 50; ++s ) { double a, b; house_gen( &h, 1 + s % 5, s ); house_size( 1 + s % 5, s, &a, &b ); CHECK( a == h.lx && b == h.dy ); }
    // the same seed, the same house
    house_t h2;
    house_gen( &h, 3, 77 ); house_gen( &h2, 3, 77 );
    CHECK( memcmp( &h, &h2, sizeof(h) ) == 0 );
    house_gen( &h2, 3, 78 );
    CHECK( memcmp( &h, &h2, sizeof(h) ) != 0 );
}

static void test_walk( void ) {
    house_t h;
    int nbad = 0, nh = 0, rooms = 0;
    for ( int t = 1; t <= 5; ++t ) {
        for ( int s = 1; s <= 400; ++s ) {
            house_gen( &h, t, s );
            int u = house_unreachable( &h );
            ++nh;
            if ( u != 0 ) { ++nbad; rooms += u; if ( nbad <= 10 ) { printf( "house type %d seed %d: %d room(s) cannot be reached\n", t, s, u ); } }
        }
    }
    printf( "walkable: %d of %d houses have a room one cannot reach (%d rooms)\n", nbad, nh, rooms );
    CHECK( nbad == 0 );
}

static void test_inside( void ) {
    house_t h;
    int bad = 0, degenerate = 0, minn = 1 << 30, maxn = 0;
    for ( int t = 1; t <= 5; ++t ) {
        for ( int s = 1; s <= 20; ++s ) {
            house_gen( &h, t, s );
            int prev = 1 << 30;
            for ( int stage = 0; stage < 5; ++stage ) {
                hmesh_t m;
                CHECK( house_mesh_inside( &h, stage, &m ) );
                if ( stage == 0 ) { if ( m.nt < minn ) { minn = m.nt; } if ( m.nt > maxn ) { maxn = m.nt; } }
                if ( m.nt > prev + 40 ) { ++bad; }                             // the damage only takes away (the colour of a piece may change, never its number grows much)
                prev = m.nt;
                for ( int i = 0; i < m.nv; ++i ) {
                    const hvert_t* v = &m.v[i];
                    if ( !( isfinite( v->x ) && isfinite( v->y ) && isfinite( v->z ) ) || v->x < -2 || v->x > 260 * 3.125 || v->y < -70 || v->y > 240 * 3.125 || v->z < -70 || v->z > 70 * 3.125 ) { ++bad; }
                }
                for ( int i = 0; i < m.nt; ++i ) {
                    const htri_t* tr = &m.t[i];
                    if ( tr->a < 0 || tr->b < 0 || tr->c < 0 || tr->a >= m.nv || tr->b >= m.nv || tr->c >= m.nv || tr->mat < 0 || tr->mat >= HM_NMAT ) { ++bad; continue; }
                    const hvert_t *a = &m.v[tr->a], *b = &m.v[tr->b], *c = &m.v[tr->c];
                    double e1[3] = { b->x - a->x, b->y - a->y, b->z - a->z }, e2[3] = { c->x - a->x, c->y - a->y, c->z - a->z };
                    double nx = e1[1] * e2[2] - e1[2] * e2[1], ny = e1[2] * e2[0] - e1[0] * e2[2], nz = e1[0] * e2[1] - e1[1] * e2[0];
                    if ( nx * nx + ny * ny + nz * nz < 1e-12 ) { ++degenerate; }
                }
                house_mesh_free( &m );
            }
        }
    }
    printf( "house insides (stage 0): %d .. %d triangles\n", minn, maxn );
    CHECK( bad == 0 );
    CHECK( degenerate == 0 );
    CHECK( minn >= 200 && maxn <= 6000 );
}

static void test_mesh( void ) {
    house_t h;
    int minl1 = 1 << 30, maxl1 = 0, minl0 = 1 << 30, maxl0 = 0, bad = 0, degenerate = 0, outward = 0, wallsn = 0;
    for ( int t = 1; t <= 5; ++t ) {
        for ( int s = 1; s <= 20; ++s ) {
            house_gen( &h, t, s );
            for ( int stage = 0; stage < 5; ++stage ) {
                int ntl[2] = { 0, 0 };
                for ( int level = 0; level < 2; ++level ) {
                    hmesh_t m;
                    CHECK( house_mesh( &h, stage, level, &m ) );
                    CHECK( m.nt > 0 && m.nv > 0 );
                    ntl[level] = m.nt;
                    for ( int i = 0; i < m.nv; ++i ) {
                        const hvert_t* v = &m.v[i];
                        if ( !( isfinite( v->x ) && isfinite( v->y ) && isfinite( v->z ) ) || v->x < -20 * 3.125 || v->x > 230 * 3.125 || v->y < -20 * 3.125 || v->y > 190 * 3.125 || v->z < -70 || v->z > 110 * 3.125 ) { ++bad; }
                    }
                    for ( int i = 0; i < m.nt; ++i ) {
                        const htri_t* tr = &m.t[i];
                        if ( tr->a < 0 || tr->b < 0 || tr->c < 0 || tr->a >= m.nv || tr->b >= m.nv || tr->c >= m.nv || tr->mat < 0 || tr->mat >= HM_NMAT ) { ++bad; continue; }
                        const hvert_t *a = &m.v[tr->a], *b = &m.v[tr->b], *c = &m.v[tr->c];
                        double e1[3] = { b->x - a->x, b->y - a->y, b->z - a->z }, e2[3] = { c->x - a->x, c->y - a->y, c->z - a->z };
                        double nx = e1[1] * e2[2] - e1[2] * e2[1], ny = e1[2] * e2[0] - e1[0] * e2[2], nz = e1[0] * e2[1] - e1[1] * e2[0];
                        double len = sqrt( nx * nx + ny * ny + nz * nz );
                        if ( len < 1e-9 ) { ++degenerate; continue; }
                        if ( ( t == 1 || t == 3 ) && stage == 0 && level == 1 && tr->mat == HM_PLASTER && fabs( nz / len ) < 0.5 ) {      // an outer wall of the plain houses faces away from the middle
                            double cx = ( a->x + b->x + c->x ) / 3 - h.lx * 3.125 / 2, cy = ( a->y + b->y + c->y ) / 3 - h.dy * 3.125 / 2;
                            ++wallsn;
                            if ( nx * cx + ny * cy > 0 ) { ++outward; }
                        }
                    }
                    if ( level == 0 ) { if ( m.nt < minl0 ) { minl0 = m.nt; } if ( m.nt > maxl0 ) { maxl0 = m.nt; } }
                    else              { if ( m.nt < minl1 ) { minl1 = m.nt; } if ( m.nt > maxl1 ) { maxl1 = m.nt; } }
                    house_mesh_free( &m );
                }
                CHECK( ntl[0] <= ntl[1] );
            }
        }
    }
    printf( "house meshes: far %d .. %d triangles, middle %d .. %d; %d outer wall triangles of the plain houses, %d facing outward\n", minl0, maxl0, minl1, maxl1, wallsn, outward );
    CHECK( bad == 0 );
    CHECK( degenerate == 0 );
    CHECK( wallsn > 100 && outward == wallsn );
    CHECK( minl0 >= 20 && maxl0 <= 1500 && minl1 >= 100 && maxl1 <= 4000 );
    // the same house twice gives the same mesh; a house of another seed another one
    hmesh_t a, b;
    house_gen( &h, 5, 9 );
    CHECK( house_mesh( &h, 2, 1, &a ) && house_mesh( &h, 2, 1, &b ) );
    CHECK( a.nt == b.nt && a.nv == b.nv && memcmp( a.v, b.v, sizeof(hvert_t) * (size_t) a.nv ) == 0 && memcmp( a.t, b.t, sizeof(htri_t) * (size_t) a.nt ) == 0 );
    house_mesh_free( &a ); house_mesh_free( &b );
    // a stage that is gone stays gone: the triangles of the roof (material HM_ROOF) never grow with the damage
    for ( int t = 1; t <= 5; ++t ) {
        house_gen( &h, t, 5 );
        int prev = 1 << 30;
        for ( int stage = 0; stage < 5; ++stage ) {
            hmesh_t m;
            CHECK( house_mesh( &h, stage, 1, &m ) );
            int nr = 0;
            for ( int i = 0; i < m.nt; ++i ) { if ( m.t[i].mat == HM_ROOF ) { ++nr; } }
            CHECK( nr <= prev );
            prev = nr;
            house_mesh_free( &m );
        }
    }
}

