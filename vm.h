/*
Minimal executor for the instruction set defined in instset.h.

It runs the code generated by codegen into codegen_t.code / .data and uses a varmem_t for variables.
The data stack items are either a number or a string pointer (heap, NUL-terminated); they are tagged, so a
type mismatch is a run time error and strings never leak.
The stacks are heap allocated and grow on demand.

Not implemented yet (reported as errors at run time): BRK, WRLV, array parameters of functions.

DATA: the VM keeps the data pointer (vm_t.datapos); vm_run() resets it to the first item (like RESTORE), vm_run_at() leaves it.

Policies chosen by this implementation (the instruction set does not define them):
    - comparisons yield -1 (true) or 0 (false)
    - bitwise operations convert their operands to 32 bit signed integers
    - PNUM / PSTR separator parameter: 0 = none (newline follows), 4 = semicolon, 8 = comma (next 10 column zone)
    - numbers are printed (and converted by STR$) with "%.15g" and no padding
    - SHEX runs the command with popen() and returns its standard output without the trailing newlines (like a shell
      command substitution); the exit status is ignored; output longer than 65535 bytes is an error
    - LOAD and RUN ( RUNP ) can't be carried out by the VM: it doesn't own the program, and the program being run would be
      replaced. The instruction stores a request (vm_t.request, reqname, reqline) and ends the run; vm_run()/vm_run_at()
      return true and the host looks at vm->request: it then replaces/recompiles the program, clears the variables (as for
      a new run) and starts the VM again. A host that ignores the request just sees the program end. The request is
      cleared at the start of the next vm_run_at().
    - LIST needs the host (list callback), which prints through the print callback to the channel vm->channel
    - SAVE ( mode name -- ) needs the host: the VM doesn't know the program, it calls the save callback (name,
      ascii) after checking the mode ("" or "B" = binary, "A" = ascii); without a callback it is an error.
      baspgm.c offers save_program() for the host to use
    - system functions:
        TI          1/60 second ticks since the VM was created
        INKEY$      the key from the inkey callback, "" if there is none (or no callback)
        INPUT       the prompt goes through the print callback, the line comes from the input callback (without a
                    callback: stdin; the host is expected to echo the typed line, so the VM sets the column to 0);
                    end of input is an error. Missing/non-numeric fields: "?Redo from start", see instset.h (INPN)
        interrupt   a running program is stopped with the error "Break" if the interrupt callback returns true; the
                    callback is also asked when the input callback returns nothing, to tell "Break" from "End of input"
        GET         waits for a key from the getkey callback; without one the inkey callback is polled every
                    millisecond; without both the key is read from stdin (getchar). Key code <= 0 = end of input (error)
        CHR$(n)     the one-character string with code n; n must be 1..255 (no NUL in strings), else an error
        FRE(x)      free variable space + free string space in bytes (the argument is ignored)
        ASC("")     is an error; LEN, VAL (leading decimal number, else 0)
        LEFT$ RIGHT$ MID$   lengths beyond the string are clamped, a negative LEFT$/RIGHT$ length and a MID$ start < 1
                            are errors; the parser supplies -1 for an omitted MID$ length (= the rest of the string)
        BIN$ QUA$ OCT$ HEX$ DEC$   (n[,digits]) convert n as a 32 bit integer, zero padded to at least <digits>
                            digits; the parser supplies -1 for omitted digits (= no padding); only DEC$ is signed,
                            the others show negative numbers as 32 bit patterns
*/

#define VMREQ_NONE          0
#define VMREQ_LOAD          1       // replace the program by the file reqname and run it from the beginning
#define VMREQ_RUN           2       // clear the variables and run the program from reqname (label) / reqline, or the start

#define VM_PRINT_SEP_NONE   UINT16_C(0)
#define VM_PRINT_SEP_SEMIC  UINT16_C(4)
#define VM_PRINT_SEP_COMMA  UINT16_C(8)
#define VM_ZONE_WIDTH       10U
#define VM_INTERRUPT_STEPS  4096U

typedef struct _vmval_t {
    bool    isstr;          // item is a string pointer, otherwise a number
    union {
        double  num;
        char*   str;
    };
} vmval_t;

// the value of a parameter variable before a function call, restored by RETF
typedef struct _vm_savedvar_t {
    uint16_t    varoffs;
    uint8_t     vartype;
    vmval_t     value;          // a string is a heap copy
} vm_savedvar_t;

typedef struct _vm_context_t {
    uint8_t         numsaved;
    vm_savedvar_t   saved[MAXPARAM];
} vm_context_t;

typedef struct _vm_t {
    codegen_t*      cgen;           // code and data segments
    varmem_t*       vmem;           // variables
    vmval_t*        dstack;         // data stack
    size_t          dsp, dmax;      // item count, allocated items
    uint16_t*       rstack;         // return stack
    size_t          rsp, rmax;
    vm_context_t*   ctxs;           // contexts of the function calls in progress
    size_t          nctx, maxctx;
    uint32_t        pc;             // offset of the next instruction
    uint32_t        datapos;        // data offset of the next DATA item (DATAOFFS_NONE = behind the last one)
    uint32_t        line;           // current line number (LINE instruction)
    uint64_t        maxsteps;       // stop with an error after this many instructions (0 = unlimited)
    int             channel;        // output channel (PCHN)
    unsigned        column;         // output column
    char*           inbuf;          // the line read by INPL, while the INPUT statement runs
    size_t          inlen, inpos;   // its length; offset of the next field (inlen + 1 = no more fields)
    uint32_t        inredo;         // code offset of the INPL instruction (restart point)
    void*           userdata;
    void            (*print)( struct _vm_t*, void*, int channel, const char* text );    // default: stdout
    void            (*report)( struct _vm_t*, void*, const char* );                     // default: stderr
    int             (*inkey)( struct _vm_t*, void* );                              // INKEY$: key code, 0 = none
    char*           (*input)( struct _vm_t*, void*, int channel );                 // INPUT: a line (malloc'd, without newline), 0 = end of input
    int             (*getkey)( struct _vm_t*, void*, int channel );                // GET: waits for a key code (1..255), <= 0 = end of input
    bool            (*interrupt)( struct _vm_t*, void* );                          // polled every VM_INTERRUPT_STEPS instructions and when INPUT/GET get no input: true = stop ("Break")
    bool            (*save)( struct _vm_t*, void*, const char* filename, bool ascii );  // SAVE: the host saves the program
    // LIST: the host lists the program to the VM's current channel; first/last are a label name ("" = none) or a line
    // number (-1 = none); a missing end is unbounded. Returns false after reporting an error.
    bool            (*list)( struct _vm_t*, void*, const char* firstlabel, int32_t firstline, const char* lastlabel, int32_t lastline );
    int             request;        // VMREQ_*: LOAD / RUN stop the VM and leave a request for the host (see vm_run_at)
    char*           reqname;        // LOAD: the file name; RUN: the label name ("" = none); owned by the VM
    int32_t         reqline;        // RUN: the line number, -1 = none
    struct timespec started;        // for the system timer TI
} vm_t;

void init_vm( vm_t* vm, codegen_t* cgen, varmem_t* vmem );
void cleanup_vm( vm_t* vm );        // frees the stacks and the strings still on the data stack
bool vm_run( vm_t* vm );            // runs from offset 0 until the end of the code; false after reporting an error
void vm_clear_request( vm_t* vm );    // forgets a pending request (frees the name)
bool vm_run_at( vm_t* vm, uint32_t start );     // same, starting at the given code offset

#endif
