/*
Minimal executor for the instruction set defined in instset.h.

It runs the code generated by codegen into codegen_t.code / .data and uses a varmem_t for variables.
The data stack items are either a number or a string pointer (heap, with a length and a trailing zero byte; a string may contain zero bytes); they are tagged, so a
type mismatch is a run time error and strings never leak.
The stacks are heap allocated and grow on demand.

Not implemented yet (reported as errors at run time): WRLV, array parameters of functions.

BRK reports "Breakpoint" as an error, unless the host turned vm_t.debug on (the monitor does): then it stops the run
(VMSTOP_BRK) and vm_resume() continues behind it. Debugging API: vm_begin() prepares a run, vm_resume() runs until the end,
a breakpoint address (vm_t.breakpoints), BRK or, with singlestep, one instruction; the VM stays suspended (vm_t.suspended)
with all its state until the run is resumed or begun again.

DATA: the VM keeps the data pointer (vm_t.datapos); vm_run() resets it to the first item (like RESTORE), vm_run_at() leaves it.

Policies chosen by this implementation (the instruction set does not define them):
    - comparisons yield -1 (true) or 0 (false)
    - bitwise operations convert their operands to 32 bit signed integers
    - PNUM / PSTR separator parameter: 0 = none (newline follows), 4 = semicolon, 8 = comma (next 10 column zone)
    - numbers are printed (and converted by STR$) with "%.15g" and no padding
    - SHEX runs the command with popen() and returns its standard output without the trailing newlines (like a shell
      command substitution); the exit status is ignored; output longer than 65535 bytes is an error
    - DELETE and RENUM (DELE, RENM) call the host (deletelines / renumber callbacks) and end the run afterwards
    - MON (MONITOR) leaves a request (VMREQ_MONITOR) and ends the run, like NEW
    - SND (SOUND, PLAY, WAVE, TEMPO, SOUND OFF/SYNC) and PLNG (PLAYING) use vm_t.sound; channels are 1..8 in BASIC (0..7 in the
      callbacks). PLAY parses all its strings (mml.h) before anything is queued: a wrong string is an error and queues nothing.
      PLAY first syncs the voices' channels, so the voices start together (after what the channels still have queued); the
      duration in the strings is in seconds (the T command), converted to the host's beats with getbpm()
    - EDIT leaves a request, too (VMREQ_EDIT: the host lets the user edit a line and enters the result like a typed line)
    - NEW (like LOAD and RUN) leaves a request; CLR (CLEAR) is done by the VM itself (vmem_clear_vars)
    - LOAD and RUN ( RUNP ) can't be carried out by the VM: it doesn't own the program, and the program being run would be
      replaced. The instruction stores a request (vm_t.request, reqname, reqline) and ends the run; vm_run()/vm_run_at()
      return true and the host looks at vm->request: it then replaces/recompiles the program, clears the variables (as for
      a new run) and starts the VM again. A host that ignores the request just sees the program end. The request is
      cleared at the start of the next vm_run_at().
    - LIST needs the host (list callback), which prints through the print callback to the channel vm->channel
    - SAVE ( mode name -- ) needs the host: the VM doesn't know the program, it calls the save callback (name,
      ascii) after checking the mode ("" or "B" = binary, "A" = ascii); without a callback it is an error.
      baspgm.c offers save_program() for the host to use
    - system functions:
        TI          1/60 second ticks since the VM was created
        INKEY$      the key from the inkey callback, "" if there is none (or no callback)
        INPUT       the prompt goes through the print callback, the line comes from the input callback (without a
                    callback: stdin; the host is expected to echo the typed line, so the VM sets the column to 0);
                    end of input is an error. Missing/non-numeric fields: "?Redo from start", see instset.h (INPN)
        interrupt   a running program is stopped with the error "Break" if the interrupt callback returns true; the
                    callback is also asked when the input callback returns nothing, to tell "Break" from "End of input"
        GET         waits for a key from the getkey callback; without one the inkey callback is polled every
                    millisecond; without both the key is read from stdin (getchar). Key code <= 0 = end of input (error)
        CHR$(n)     the one-character string with code n; n must be 0..255, else an error
        FRE(x)      free variable space + free string space in bytes (the argument is ignored)
        ASC("")     is an error; LEN, VAL (leading decimal number, else 0)
        LEFT$ RIGHT$ MID$   lengths beyond the string are clamped, a negative LEFT$/RIGHT$ length and a MID$ start < 1
                            are errors; the parser supplies -1 for an omitted MID$ length (= the rest of the string)
        BIN$ QUA$ OCT$ HEX$ DEC$   (n[,digits]) convert n as a 32 bit integer, zero padded to at least <digits>
                            digits; the parser supplies -1 for omitted digits (= no padding); only DEC$ is signed,
                            the others show negative numbers as 32 bit patterns
*/

#define VMREQ_NONE          0
#define VMREQ_LOAD          1       // replace the program by the file reqname and run it from the beginning
#define VMREQ_NEW           3       // delete the program and the variables; the run is not continued
#define VMREQ_RUN           2       // clear the variables and run the program from reqname (label) / reqline, or the start
#define VMREQ_EDIT          4       // let the user edit the line reqline / the line of the label reqname; the run is not continued
#define VMREQ_MONITOR       5       // open the machine monitor; the run is not continued
#define VMREQ_CHAIN         6       // load (reqmerge: merge) the file reqname and run the program from reqlabel / reqline, keeping variables

// why vm_resume() returned (vm_t.stopreason): VMSTOP_NONE = the run is over (the code ended, an error was reported, or a
// request was left), the others leave the VM suspended: the stacks, the pc and everything else stay as they are and
// vm_resume() continues
#define VMSTOP_NONE         0
#define VMSTOP_STEP         1       // one instruction was run (single-step)
#define VMSTOP_BREAKPOINT   2       // pc is at an address of vm_t.breakpoints; the instruction there has not run yet
#define VMSTOP_BRK          3       // a BRK instruction ran (only with vm_t.debug; pc is behind it)

#define VM_PRINT_SEP_NONE   UINT16_C(0)
#define VM_PRINT_SEP_SEMIC  UINT16_C(4)
#define VM_PRINT_SEP_COMMA  UINT16_C(8)
#define VM_ZONE_WIDTH       10U
#define VM_INTERRUPT_STEPS  4096U

typedef struct _vm_field_t {
    int             chan;           // the random file
    uint16_t        var;            // the variable number of the string variable
    uint32_t        off, len;       // the part of the record
} vm_field_t;

typedef struct _vmval_t {
    bool    isstr;          // item is a string pointer, otherwise a number
    uint32_t len;           // strings: the length in bytes (a string may contain zero bytes; a trailing zero byte is always there as well)
    union {
        double  num;
        char*   str;
    };
} vmval_t;

// the value of a parameter variable before a function call, restored by RETF
typedef struct _vm_savedvar_t {
    uint16_t    varoffs;
    uint8_t     vartype;
    vmval_t     value;          // a string is a heap copy
} vm_savedvar_t;

typedef struct _vm_context_t {
    size_t          rsp;            // the return stack depth before the call (to unwind after an error)
    uint8_t         numsaved;
    vm_savedvar_t   saved[MAXPARAM];
} vm_context_t;

// The host's sound output (SOUND, PLAY, ... , PLAYING; all callbacks required when a vm_t.sound is given). Channels are 0..7
// here. The calls only queue: they return at once. beats are in the unit of the host's tempo (see TEMPO).
typedef struct _vm_sound_t {
    void    (*tone)( void* usrdata, int chan, float freq, float freq2, float vol, float beats );   // a tone for "beats" (freq 0 = a
                                                                // rest; freq2 != 0: the pitch glides to it during the tone)
    void    (*setwave)( void* usrdata, int chan, int wave );
    void    (*setenv)( void* usrdata, int chan, float attack, float decay, float sustain, float release );   // attack < 0 = default
    void    (*setvib)( void* usrdata, int chan, float rate, float depth );
    void    (*settrem)( void* usrdata, int chan, float rate, float depth );
    void    (*setpitch)( void* usrdata, int chan, float freq );     // at once
    void    (*setvolume)( void* usrdata, int chan, float vol );     // at once
    void    (*setbpm)( void* usrdata, int bpm );
    int     (*getbpm)( void* usrdata );                     // the tempo; 0 = unknown (60 is assumed)
    void    (*sync)( void* usrdata, unsigned chanmask );    // lines up the time of the channels in the mask
    void    (*silence)( void* usrdata, int chan );          // now: drops what is queued for the channel, fades it out; -1 = all
    bool    (*busy)( void* usrdata, int chan );             // the channel sounds, or has events queued / a sequence running
} vm_sound_t;

#define VM_NTIMERS          4

#define VM_ADDRLEN          20

typedef struct _vm_timer_t {
    bool        active;
    bool        every;          // repeats (EVERY), else once (AFTER)
    bool        gosub;          // the handler is called (GOSUB), else jumped to (GOTO)
    uint64_t    due;            // monotonic nanoseconds
    uint64_t    interval;       // nanoseconds
    uint32_t    target;         // code address of the handler
} vm_timer_t;

typedef struct _vm_irq_t {      // a handler that is running: where the return stack was and what the line was
    int         timer;
    size_t      rsp;
    uint32_t    line;
} vm_irq_t;

typedef struct _vm_t {
    codegen_t*      cgen;           // code and data segments
    varmem_t*       vmem;           // variables
    vmval_t*        dstack;         // data stack
    size_t          dsp, dmax;      // item count, allocated items
    uint32_t*       rstack;         // return stack (code addresses, function call frames)
    size_t          rsp, rmax;
    vm_context_t*   ctxs;           // contexts of the function calls in progress
    size_t          nctx, maxctx;
    uint32_t        pc;             // offset of the next instruction
    uint32_t        datapos;        // data offset of the next DATA item (DATAOFFS_NONE = behind the last one)
    uint32_t        line;           // current line number (LINE instruction)
    uint64_t        maxsteps;       // stop with an error after this many instructions (0 = unlimited)
    // debugging (set by the host before vm_resume(); the VM doesn't keep them across init_vm())
    bool            debug;          // BRK stops the run (VMSTOP_BRK) instead of reporting "Breakpoint"
    const uint32_t* breakpoints;    // code offsets where the run stops before the instruction; not owned
    size_t          nbreakpoints;
    int             stopreason;     // VMSTOP_*
    bool            brkhit;         // (internal) a BRK instruction ran
    bool            suspended;      // vm_begin() / a stop of vm_resume() left a run that vm_resume() can continue
    int             channel;        // output channel (PCHN)
    unsigned        column;         // output column
    char*           inbuf;          // the line read by INPL, while the INPUT statement runs
    size_t          inlen, inpos;   // its length; offset of the next field (inlen + 1 = no more fields)
    uint32_t        inredo;         // code offset of the INPL instruction (restart point)
    void*           userdata;
    void            (*print)( struct _vm_t*, void*, int channel, const char* text );    // default: stdout
    // optional: the same for text with zero bytes (they are characters: the glyphs of the control codes); without it the text is
    // handed to print() in pieces and the zero bytes are left out
    void            (*printn)( struct _vm_t*, void*, int channel, const char* text, size_t len );
    void            (*report)( struct _vm_t*, void*, const char* );                     // default: stderr
    int             (*inkey)( struct _vm_t*, void* );                              // INKEY$: key code, 0 = none
    char*           (*input)( struct _vm_t*, void*, int channel );                 // INPUT: a line (malloc'd, without newline), 0 = end of input
    int             (*getkey)( struct _vm_t*, void*, int channel );                // GET: waits for a key code (1..255), <= 0 = end of input
    bool            (*interrupt)( struct _vm_t*, void* );                          // polled every VM_INTERRUPT_STEPS instructions and when INPUT/GET get no input: true = stop ("Break")
    bool            (*save)( struct _vm_t*, void*, const char* filename, bool ascii );  // SAVE: the host saves the program
    // LIST: the host lists the program to the VM's current channel; first/last are a label name ("" = none) or a line
    // number (-1 = none); a missing end is unbounded. Returns false after reporting an error.
    bool            (*list)( struct _vm_t*, void*, const char* firstlabel, int32_t firstline, const char* lastlabel, int32_t lastline );
    // DELETE / RENUMBER: the host edits the stored program (ranges as for list); the VM ends the run afterwards, because the
    // running code no longer matches the program. Return false after reporting an error.
    bool            (*deletelines)( struct _vm_t*, void*, const char* firstlabel, int32_t firstline, const char* lastlabel, int32_t lastline );
    // MERGE: merges the program file <name> into the stored program (append: behind its last line, renumbered). Return false after
    // reporting an error. The run ends afterwards.
    // FILES: lists the files of spec ("" = the current directory) to the current output channel. Return false after reporting an error.
    bool            (*files)( struct _vm_t*, void*, const char* spec );
    bool            (*merge)( struct _vm_t*, void*, const char* name, bool append );
    bool            (*renumber)( struct _vm_t*, void*, const char* firstlabel, int32_t firstline, const char* lastlabel, int32_t lastline, int32_t step );
    bool            sfx_defined[SND_MAXSFX];
    mml_t           sfx[SND_MAXSFX];    // the stored sound effects (SFX n, a$), parsed; cleared with the VM
    const vm_sound_t* sound;        // SOUND / PLAY / ...: the host's sound output; 0 = none (arguments are checked, nothing plays)
    // AFTER / EVERY: four timers (the numbers are priorities: a handler can only be interrupted by a higher number)
    vm_timer_t      timers[VM_NTIMERS];
    int             numtimers;      // active timers
    vm_irq_t        irq[VM_NTIMERS];    // the GOSUB handlers that are running, innermost last
    int             irqdepth;
    bool            irqpending;     // (internal) a timer is due but the program is not between two statements yet
    bool            irqsafe;        // (internal) a handler may be entered although the stack isn't empty (WAIT gave way to it)
    // I/O subsystem (docs/io-subsystem.md): the channels opened with OPEN, and the default driver of ADDRESS
    // ON ERROR
    bool            errset;         // a handler is set (and not running)
    bool            errgosub;       // the handler was set with GOSUB
    uint32_t        errtarget;      // its code address
    bool            errinhandler;   // a GOSUB handler is running: errors are not caught
    size_t          errrsp;         // the return stack depth below the handler's return address
    bool            errcaught;      // (internal) vm_error() kept an error for the handler
    char            errtext[160];   // (internal) that error
    uint32_t        errtextline;
    char            errlast[160];   // ERR$ and ERL: the last caught error
    uint32_t        errlastline;
    iotab_t         io;
    struct _vm_field_t* fields;     // FIELD: the string variables bound to parts of the record buffers of random files
    size_t          numfields, capfields;
    char            addrcur[VM_ADDRLEN], addrprev[VM_ADDRLEN];
    const char*     iofail;         // (internal) a message of an I/O error that happened where it can't be reported at once
    const char*     inerr;          // (internal) why vm_get_line() returned nothing (a file channel)
    int             request;        // VMREQ_*: LOAD / RUN stop the VM and leave a request for the host (see vm_run_at)
    char*           reqname;        // LOAD: the file name; RUN: the label name ("" = none); owned by the VM
    int32_t         reqline;        // RUN: the line number, -1 = none
    char*           reqlabel;       // CHAIN: the label to start at ("" = none); owned by the VM
    bool            reqmerge;       // CHAIN: merge the file instead of replacing the program
    struct timespec started;        // for the system timer TI
} vm_t;

void init_vm( vm_t* vm, codegen_t* cgen, varmem_t* vmem );
void cleanup_vm( vm_t* vm );        // frees the stacks and the strings still on the data stack
bool vm_run( vm_t* vm );            // runs from offset 0 until the end of the code; false after reporting an error
void vm_clear_request( vm_t* vm );    // forgets a pending request (frees the name)
bool vm_run_at( vm_t* vm, uint32_t start );     // same, starting at the given code offset
bool vm_begin( vm_t* vm, uint32_t start );      // prepares a run (clears the stacks and the request, pc = start) without running it
// runs from pc until the end of the code, a breakpoint (the instruction at the very first pc always runs, so that a run
// can leave a breakpoint) or BRK; with singlestep exactly one instruction. false after reporting an error. See VMSTOP_*.
bool vm_resume( vm_t* vm, bool singlestep );

#endif
