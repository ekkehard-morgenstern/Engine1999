# Makes the VM instruction reference docs/vm-instructions.md from the specification in instset.h:
#
#   perl instref.pl            writes docs/vm-instructions.md
#   perl instref.pl --check    writes nothing: fails if the file is out of date, if an instruction of the specification comment has a different
#                              code than its #define INS_xxx, or if a #define has no entry in the specification (run "perl instref.pl")
#
# instset.h is the source: the lines "0001 00010100  ADD - text ( stack ) C=0 P=0" of its big comment, with the more indented lines that follow
# as details, and the #define INS_xxx values (the codes the VM and the code generator really use). The prose parts are in this script.

use strict;
use warnings;

my $check = @ARGV && $ARGV[0] eq '--check';
my $dir = $0 =~ m{^(.*)/[^/]*$} ? $1 : '.';
my $src = "$dir/instset.h";
my $out = "$dir/docs/vm-instructions.md";

open( my $fh, '<', $src ) or die "$src: $!\n";
my @lines = <$fh>;
close $fh;
chomp @lines;

# -- the #defines --------------------------------------------------------------------------------------------------------------------
my %def;        # name => code (extended: the 12 bit value; basic: 0..15)
my %defbasic;
for my $l ( @lines ) {
    if ( $l =~ /^#define\s+INS_([A-Z0-9]+)\s+UINT16_C\(0[Xx]([0-9A-Fa-f]+)\)/ ) {
        $def{$1} = hex( $2 );
    } elsif ( $l =~ /^#define\s+INS_([A-Z0-9]+)\s+MKINS_I\((\d+)\)/ ) {
        $defbasic{$1} = $2 + 0;
    }
}

# -- the specification comment -------------------------------------------------------------------------------------------------------
my @ins;        # { code, name, head, stack, cp, details => [] }
my $cur;
my $in_comment = 0;
my %seen;
for my $l ( @lines ) {
    if ( $l =~ /^\/\*\s*$/ ) { $in_comment = 1; next; }
    if ( $l =~ /^\*\/\s*$/ ) { $in_comment = 0; undef $cur; next; }
    next unless $in_comment;
    if ( $l =~ /^    ([01]{4}) ([01]{8})\s+([A-Z0-9]+)\s+-\s+(.*?)\s*$/ ) {
        my ( $hi, $lo, $name, $rest ) = ( $1, $2, $3, $4 );
        my $code = oct( "0b$hi$lo" );
        die "instset.h: $name is listed twice in the specification\n" if $seen{$name}++;
        die "instset.h: $name is in the specification as " . sprintf( '0x%03X', $code ) . " but has no #define\n" unless exists $def{$name};
        die sprintf( "instset.h: %s is 0x%03X in the specification but 0x%03X in its #define\n", $name, $code, $def{$name} ) if $def{$name} != $code;
        my ( $stack, $cp ) = ( '', '' );
        $cp = "$1 $2" if $rest =~ s/\s+(C=[01])\s+(P=[01](?:\/[01])?)(;?)\s*/$3 /;
        $stack = $1 if $rest =~ s/\s*(R?\(\s.*?\s\))//;
        $rest =~ s/\s+$//;
        $cur = { code => $code, name => $name, head => $rest, stack => $stack, cp => $cp, details => [] };
        push @ins, $cur;
        next;
    }
    if ( $cur && $l =~ /^                        (\S.*)$/ ) {
        push @{ $cur->{details} }, $1;
        next;
    }
    if ( $cur && $l =~ /^                          +(\S.*)$/ ) {
        push @{ $cur->{details} }, "  $1";
        next;
    }
    undef $cur if $l =~ /^\s*$/ || $l =~ /^    \S/;
}
my @missing = sort grep { !$seen{$_} } keys %def;
# an instruction that has a #define but is not in the specification comment is listed in the output

# -- the output ----------------------------------------------------------------------------------------------------------------------
my @o;
push @o, '# VM instruction reference';
push @o, '';
push @o, '*Generated by `perl instref.pl` from `instset.h` (the specification: change that, then run `make vmref`; `make vmref-check` fails when this file is out of date). Do not edit this file.*';
push @o, '';
push @o, 'The VM (`vm.[ch]`) is a stack machine that runs the code the code generator (`codegen.c`, `cgen*.c`) makes from the syntax tree (`docs/compiler-and-vm.md`). This page lists every instruction: its code, the stack effect, how its parameter is used, and the details of the specification. The machine monitor (`MONITOR`) and `vmasm.[ch]` (the VM assembler / decoder) use the same mnemonics.';
push @o, '';
push @o, '## The machine';
push @o, '';
push @o, '- **Data stack:** items of 64 bit: a floating-point number (`n`) or a pointer to a string on the heap (`s`). An instruction removes its operands; an instruction with a string operand frees it. Strings are binary safe (a length, no terminator), at most 65535 bytes.';
push @o, '- **Return stack:** 32 bit code addresses (`a`) and, for a call of a `PROC` / `FUNC`, the context that restores the parameter variables. `GOSUB` pushes on it too (`RTRP` tells the two apart).';
push @o, '- **Code and data segments:** 32 bit offsets that grow on demand. Variables live in `vars.[ch]` and are addressed by a variable number (`varoffs`). All multi-byte values in code are **big endian**.';
push @o, '- **Notation** (as in FORTH): `( n1 n2 -- n )` is "takes n1, then n2; leaves n"; `R( a -- )` is the return stack; `n` number, `s` string, `a` address, `inx ... ndim` array subscripts followed by their count.';
push @o, '- **Resumable:** the VM stops cleanly between instructions (single step, breakpoints, `WAIT`, timers, requests to the host such as `LOAD` / `RUN` / `NEW` / `EDIT` / `MONITOR`), so a host loop can run it again with `vm_resume()`. Run-time errors go to `ON ERROR` handlers or stop the program with the message and line number.';
push @o, '';
push @o, '## Encoding';
push @o, '';
push @o, '```';
push @o, '<ins> [ <ext> ] [ <hi> <lo> ]          or, with the W flag:   <ins> [ <ext> ] [ <b3> <b2> <b1> <b0> ]';
push @o, '';
push @o, 'instruction byte:   P C E W | I I I I';
push @o, '```';
push @o, '';
push @o, '| Flag | Bit | Meaning |';
push @o, '|---|---|---|';
push @o, '| P | 0x80 | a parameter field follows |';
push @o, '| C | 0x40 | the parameter or stack is of the *code* (return stack, code address), not the data kind |';
push @o, '| E | 0x20 | extended instruction: one more byte follows; the 4 bits of the instruction byte become the high bits of a 12 bit code, the extension byte the low 8 |';
push @o, '| W | 0x10 | wide: the parameter has 32 bits instead of 16 (only with P) |';
push @o, '| I | 0x0F | the instruction field (the 16 basic instructions, or the high 4 bits of an extended one) |';
push @o, '';
push @o, 'The code generator uses the short form where a value fits (variable numbers, small data offsets, small immediates) and the wide form for everything that can exceed 65535: code addresses (always, they are patched after the instruction was generated), data offsets, line numbers and large immediates. In an extended instruction the C and P bits belong to the instruction as listed below.';
push @o, '';
push @o, '## Basic instructions (code in the instruction byte, bits 0..3)';
push @o, '';
my %bdesc = (
    BRK  => [ 'a breakpoint (reports "Breakpoint"; C and P ignored)', '' ],
    NOP  => [ 'no operation (C and P ignored)', '' ],
    PHPA => [ 'push the parameter as an address: C=0 onto the data stack (as a number), C=1 onto the return stack (as an integer); P must be set', '( -- n ) or R( -- a )' ],
    PHIM => [ 'push an immediate: 17 bits (C is the 17th bit, sign-extended) or, with W, a signed 32 bit value (C ignored); converted to a number', '( -- n )' ],
    BRIA => [ 'branch to an immediate code address (17 bits with C, or 32 bits with W; the generator always uses the wide form); out of range is a run-time error', '' ],
    BRIR => [ 'branch relative to the following instruction (signed 17 / 32 bit offset)', '' ],
    JPCC => [ 'quick conditional jump: continue at the code address from the return stack if the number is nonzero (C=1, P=0)', '( n -- ) R( a -- )' ],
    JUMP => [ 'quick jump: pull a code address from the return stack and go there (C=1, P=0); `GOSUB` / `RETURN` use it', 'R( a -- )' ],
    DROP => [ 'drop items (parameter = how many, default 1) from the data stack (C=0, 8 bytes each) or the return stack (C=1)', '( n -- ) or R( a -- )' ],
    LINE => [ 'set the current line number (the first instruction of every program line; P set, C=0); errors, `TRACE`, `ERL` and the monitor use it', '' ],
    LAN  => [ 'load a number from a code or data address on the stack (C selects the segment; the address is a floating-point number)', '( n -- n )' ],
    LIAN => [ 'load a signed integer from an address and convert it to a number', '( n -- n )' ],
    LUAN => [ 'load an unsigned integer from an address and convert it to a number', '( n -- n )' ],
    LAS  => [ 'load a string constant from an address (a new heap string)', '( n -- s )' ],
    FRES => [ 'free a string pointer from the data stack (C=0)', '( s -- )' ],
);
push @o, '| Code | Mnemonic | Stack | What it does |';
push @o, '|---|---|---|---|';
for my $n ( sort { $defbasic{$a} <=> $defbasic{$b} } grep { !/_[CD]$/ } keys %defbasic ) {
    my $d = $bdesc{$n} or die "instref.pl: no description for the basic instruction $n\n";
    push @o, sprintf( '| 0x%X | `%s` | %s | %s |', $defbasic{$n}, $n, $d->[1] ne '' ? '`' . $d->[1] . '`' : '', $d->[0] );
}
push @o, '| 0xF | | | reserved |';
push @o, '';
push @o, '`PHPA` has two named forms in the code generator: `PHPA.C` (C=1, the return stack) and `PHPA.D` (C=0, the data stack).';
push @o, '';
push @o, '## Extended instructions (12 bit code)';
push @o, '';
push @o, 'The first group (0x01x, 0x02x) is arithmetic, logic and comparison; 0x1xx are the variable, call, I/O, string, system and host instructions. "C P" is the flag pair the instruction is generated with (`P=0/1`: both forms exist). The stack effect is in the notation above.';
push @o, '';
push @o, '| Code | Mnemonic | Stack | C P | What it does |';
push @o, '|---|---|---|---|---|';
for my $i ( sort { $a->{code} <=> $b->{code} } @ins ) {
    my $h = $i->{head};
    $h =~ s/\|/\\|/g;
    my $st = $i->{stack};
    $st =~ s/\|/\\|/g;
    push @o, sprintf( '| 0x%03X | `%s` | %s | %s | %s |', $i->{code}, $i->{name}, $st ne '' ? '`' . $st . '`' : '', $i->{cp}, $h );
}
if ( @missing ) {
    push @o, '';
    push @o, '**Defined in `instset.h` but without an entry in its specification comment** (they exist in the VM; see the source `vm.c` / `codegen.c`): ' . join( ', ', map { sprintf( '`%s` (0x%03X)', $_, $def{$_} ) } sort { $def{$a} <=> $def{$b} } @missing ) . '.';
}
push @o, '';
push @o, '## Details of the extended instructions';
push @o, '';
push @o, 'The text of the specification, instruction by instruction (only those that have more to say than the table).';
push @o, '';
for my $i ( sort { $a->{code} <=> $b->{code} } @ins ) {
    next unless @{ $i->{details} };
    push @o, sprintf( '### `%s` (0x%03X)', $i->{name}, $i->{code} );
    push @o, '';
    push @o, '```';
    push @o, @{ $i->{details} };
    push @o, '```';
    push @o, '';
}
push @o, '## Fused instructions';
push @o, '';
push @o, 'At run time `vm.c` maps the address of some instruction sequences (`RRNV;RRNV;ADD`, a counting loop test, one and two dimensional array element access, ...) to a **fused handler** through a lazily filled side table. The code does not change (the monitor, `LIST` and jumps into the middle of a sequence work), every handler checks its preconditions and falls back to the plain instruction, and fusing is off while single-stepping, with breakpoints, with a step limit and with `E1999_NOFUSE=1` in the environment. Details and the list of fused sequences: [compiler-and-vm.md](compiler-and-vm.md), "Fused instructions and array fast path"; `fusetest.sh` compares runs with and without fusing.';
push @o, '';
push @o, '## See also';
push @o, '';
push @o, '- `instset.h` - the specification this page is made from, and the `INS_*` codes the C code uses.';
push @o, '- `docs/compiler-and-vm.md` - how statements become instructions (code generator, `NT_*` node types, the VM loop, requests to the host).';
push @o, '- `vmasm.[ch]`, the monitor (`MONITOR`) - assemble / disassemble code with these mnemonics; `docs/basic-language.md` - what the statements mean.';
push @o, '';
my $text = join( "\n", @o );

if ( $check ) {
    open( my $in, '<', $out ) or die "instref.pl: $out is missing (run \"perl instref.pl\")\n";
    local $/;
    my $old = <$in>;
    close $in;
    if ( $old ne $text ) {
        print STDERR "instref.pl: $out is out of date (run \"perl instref.pl\")\n";
        exit 1;
    }
    print "vm-instructions.md is current (", scalar( @ins ), " documented extended instructions)\n";
    exit 0;
}
open( my $w, '>', $out ) or die "$out: $!\n";
print $w $text;
close $w;
print "wrote $out (", scalar( @ins ), " extended instructions, ", scalar( @missing ), " without a specification entry)\n";
