# Writes the version string of the build to a C header (default version.h): the newest version tag
# of git (vMAJOR.MINOR.BUILD, see bump_version.sh) with what comes after it:
#
#   v0.5.0              HEAD is the tagged commit
#   v0.5.0-3-g1a2b3c4   3 commits after the tag, the last one is 1a2b3c4
#   untagged-1a2b3c4    no version tag yet
#   unknown             not a git repository (e.g. a source archive): an existing header is kept
#
# The header is only rewritten if the string changes, so nothing is recompiled for no reason.
# Usage: sh tagtoverstr.sh [header]

out=${1:-version.h}
ver=""
desc=$(git describe --tags --long --match 'v[0-9]*.[0-9]*.[0-9]*' 2>/dev/null)
if [ -n "$desc" ]; then
    ver=$(printf '%s\n' "$desc" | sed -n 's/^\(v[0-9][0-9]*\.[0-9][0-9]*\.[0-9][0-9]*\)-0-g[0-9a-f][0-9a-f]*$/\1/p')
    [ -n "$ver" ] || ver=$desc
else
    hash=$(git rev-parse --short HEAD 2>/dev/null)
    if [ -n "$hash" ]; then
        ver="untagged-$hash"
    elif [ -f "$out" ]; then
        exit 0
    else
        ver="unknown"
    fi
fi

new=$(printf '/* generated by tagtoverstr.sh from the newest version tag of git, DO NOT MODIFY!! */\n\n#define ENGINE_VERSION  "%s"\n' "$ver")
if [ "$(cat "$out" 2>/dev/null)" != "$new" ]; then
    printf '%s\n' "$new" > "$out"
fi
